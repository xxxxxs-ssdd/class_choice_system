#Requires -Version 7.0
<#
.SYNOPSIS
  Build the DeepSeek Harness from source and wire this repository's plugins into it.

.DESCRIPTION
  The Harness checkout, its dependencies, and every build artifact live outside this
  repository (default: ../class_choice_system_contribute/deepseek-harness) so this repo
  stays uploadable. The script clones on first run, installs, builds, then writes
  profile/class-choice.overlay.yml with absolute plugin paths for the local machine.

.PARAMETER HarnessDir
  Where the deepseek-harness checkout lives. Created by cloning when missing.

.PARAMETER SkipInstall
  Reuse the existing node_modules instead of running pnpm install.

.PARAMETER SkipBuild
  Reuse existing build artifacts instead of running pnpm run build:artifacts.

.EXAMPLE
  pwsh ./scripts/setup-dev.ps1
#>
[CmdletBinding()]
param(
  [string]$HarnessDir,
  [switch]$SkipInstall,
  [switch]$SkipBuild
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

if (-not $HarnessDir) {
  $HarnessDir = Join-Path (Split-Path -Parent $repoRoot) 'class_choice_system_contribute\deepseek-harness'
}
$HarnessDir = [System.IO.Path]::GetFullPath($HarnessDir)

Write-Host "==> Harness checkout: $HarnessDir"

if (-not (Test-Path (Join-Path $HarnessDir 'package.json'))) {
  Write-Host '==> Cloning deepseek-harness (shallow)'
  git clone --depth 1 --single-branch --branch master https://github.com/deepseek-ai/deepseek-harness.git $HarnessDir
  if ($LASTEXITCODE -ne 0) { throw "git clone failed with exit code $LASTEXITCODE" }
}

Push-Location $HarnessDir
try {
  if (-not $SkipInstall) {
    Write-Host '==> pnpm install'
    pnpm install --frozen-lockfile
    if ($LASTEXITCODE -ne 0) { throw "pnpm install failed with exit code $LASTEXITCODE" }
  }

  if (-not $SkipBuild) {
    Write-Host '==> pnpm run build:artifacts'
    pnpm run build:artifacts
    if ($LASTEXITCODE -ne 0) { throw "build failed with exit code $LASTEXITCODE" }
  }
}
finally {
  Pop-Location
}

$themePlugin = Join-Path $repoRoot 'plugins\dsh-arknights-theme\src\index.ts'
$classChoicePlugin = Join-Path $repoRoot 'plugins\dsh-class-choice\src\index.ts'
foreach ($plugin in @($themePlugin, $classChoicePlugin)) {
  if (-not (Test-Path $plugin)) { throw "plugin entry not found: $plugin" }
}

$profileDir = Join-Path $repoRoot 'profile'
New-Item -ItemType Directory -Force -Path $profileDir | Out-Null
$overlayPath = Join-Path $profileDir 'class-choice.overlay.yml'

$overlay = @"
# Generated by scripts/setup-dev.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss').
# Plugin paths must be absolute: the DSH loader resolves them as-is.

- insert:
    - id: arknights-theme
      name: '$($themePlugin -replace '\\', '/')'
    - id: class-choice
      name: '$($classChoicePlugin -replace '\\', '/')'
"@
Set-Content -Path $overlayPath -Value $overlay -Encoding utf8

Write-Host "==> Wrote $overlayPath"
Write-Host ''
Write-Host 'Next:'
Write-Host "  pwsh ./scripts/dev-web.ps1 -Port 3080"
