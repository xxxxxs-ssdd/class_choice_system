#Requires -Version 7.0
<#
.SYNOPSIS
  Launch the Web UI of a source build with this repository's plugins loaded.

.DESCRIPTION
  Runs `dsh --profile web --patch <overlay>` from the Harness checkout. The overlay is
  generated by setup-dev.ps1; the printed URL carries the one-time local trust token.

.PARAMETER Port
  Listen port. Defaults to 3080.

.PARAMETER HarnessDir
  Harness checkout path. Defaults to ../class_choice_system_contribute/deepseek-harness.

.PARAMETER Open
  Let dsh open the default browser instead of only printing the URL.

.EXAMPLE
  pwsh ./scripts/dev-web.ps1 -Port 3080
#>
[CmdletBinding()]
param(
  [int]$Port = 3080,
  [string]$HarnessDir,
  [switch]$Open
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

if (-not $HarnessDir) {
  $HarnessDir = Join-Path (Split-Path -Parent $repoRoot) 'class_choice_system_contribute\deepseek-harness'
}
$HarnessDir = [System.IO.Path]::GetFullPath($HarnessDir)
$overlay = Join-Path $repoRoot 'profile\class-choice.overlay.yml'

if (-not (Test-Path $overlay)) {
  throw "overlay missing: $overlay. Run ./scripts/setup-dev.ps1 first."
}
if (-not (Test-Path (Join-Path $HarnessDir 'package.json'))) {
  throw "harness checkout missing: $HarnessDir. Run ./scripts/setup-dev.ps1 first."
}

Push-Location $HarnessDir
try {
  $arguments = @('dsh', '--profile', 'web', '--patch', $overlay, '--port', "$Port")
  if (-not $Open) { $arguments += '--no-open' }
  Write-Host "==> pnpm $($arguments -join ' ')"
  & pnpm @arguments
}
finally {
  Pop-Location
}
