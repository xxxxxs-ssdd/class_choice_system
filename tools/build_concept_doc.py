h("5.2 召回与重排", 2)
para("建议采用混合检索而非单一向量检索，原因是培养方案中大量存在课程代码、课程名称、条款编号这类**精确匹配需求**，语义向量在这类查询上反而不如关键词检索可靠。")
numbered("**并行召回**：关键词检索（倒排／BM25）与向量检索同时执行，各自取前若干条。")
numbered("**融合排序**：采用倒数排名融合（RRF）等策略合并两路结果，避免单一通道主导。")
numbered("**重排**：对融合后的候选集做一次精排（交叉编码器或由大模型打分），选出与问题真正相关的 3～6 条。")
numbered("**去重与补全**：相邻分块去重；若某条被截断，自动补齐其上下相邻块，保证语义完整。")
numbered("**权威性加权**：正式培养方案 > 管理规定 > 教学大纲 > 学院通知 > 学生经验整理，在排序中体现优先级。")
numbered("**阈值控制**：设置最低相关性阈值，低于阈值不进入生成环节，直接走拒答流程。")

