def _fld(kind, instr=None):
    if kind == "instr":
        e = OxmlElement("w:instrText")
        e.set(qn("xml:space"), "preserve")
        e.text = instr
        return e
    e = OxmlElement("w:fldChar")
    e.set(qn("w:fldCharType"), kind)
    return e


def add_toc(entries):
    """TOC 域 + 缓存结果：未更新时显示大纲，更新后显示带页码的正式目录。"""
    p0 = doc.add_paragraph()
    p0.paragraph_format.space_after = Pt(2)
    r0 = p0.add_run()
    _set_font(r0, size=10)
    for e in (_fld("begin"), _fld("instr", r'TOC \o "1-3" \h \z \u'), _fld("separate")):
        r0._element.append(e)

    last_p = p0
    for i, (lvl, text) in enumerate(entries):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.space_after = Pt(2)
        pf.line_spacing = 1.25
        if lvl == 1:
            pf.space_before = Pt(6)
            pf.left_indent = Cm(0)
            r = p.add_run(text)
            _set_font(r, ea=HEAD_EA, latin=HEAD_LATIN, size=10.5, bold=True, color=NAVY)
        else:
            pf.left_indent = Cm(0.85)
            r = p.add_run(text)
            _set_font(r, ea=BODY_EA, latin=BODY_LATIN, size=10, color=DARK)
        last_p = p

    r_end = last_p.add_run()
    _set_font(r_end, size=1)
    r_end._element.append(_fld("end"))
    return p0


