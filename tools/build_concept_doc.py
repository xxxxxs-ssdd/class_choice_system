def _set_font(run, ea=BODY_EA, latin=BODY_LATIN, size=10.5, bold=False,
              italic=False, color=DARK):
    run.font.name = latin
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), latin)
    rfonts.set(qn("w:hAnsi"), latin)
    rfonts.set(qn("w:eastAsia"), ea)


def _rich(paragraph, text, ea=BODY_EA, latin=BODY_LATIN, size=10.5,
          color=DARK):
    """支持 **加粗**、`等宽` 与 <br> 换行的行内标记。"""
    import re
    tokens = re.split(r"(\*\*.+?\*\*|`.+?`|<br\s*/?>)", text)
    for tok in tokens:
        if not tok:
            continue
        if re.fullmatch(r"<br\s*/?>", tok):
            r = paragraph.add_run()
            _set_font(r, ea=ea, latin=latin, size=size, color=color)
            r.add_break()
        elif tok.startswith("**") and tok.endswith("**") and len(tok) > 4:
            r = paragraph.add_run(tok[2:-2])
            _set_font(r, ea=ea, latin=latin, size=size, bold=True, color=color)
        elif tok.startswith("`") and tok.endswith("`") and len(tok) > 2:
            r = paragraph.add_run(tok[1:-1])
            _set_font(r, ea=MONO, latin=MONO, size=size - 0.5, color=ACCENT)
        else:
            r = paragraph.add_run(tok)
            _set_font(r, ea=ea, latin=latin, size=size, color=color)
    return paragraph


def h(text, level=1):
    p = doc.add_paragraph(style="Heading %d" % level)
    sizes = {1: 15, 2: 13, 3: 11.5, 4: 10.5}
    r = p.add_run(text)
    _set_font(r, ea=HEAD_EA, latin=HEAD_LATIN, size=sizes[level], bold=True,
              color=NAVY)
    p.paragraph_format.space_before = Pt({1: 16, 2: 12, 3: 9, 4: 7}[level])
    p.paragraph_format.space_after = Pt({1: 8, 2: 6, 3: 4, 4: 3}[level])
    p.paragraph_format.line_spacing = 1.25
    return p


def para(text, indent=True, size=10.5, align=None, space_after=5, color=DARK):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.45
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if align is not None:
        p.alignment = align
    _rich(p, text, size=size, color=color)
    return p


